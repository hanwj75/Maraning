function article(word) {
  return /^[aeiou]/i.test(word) ? 'an' : 'a'
}

function createDistractors(stages, index) {
  return Array.from({ length: 5 }, (_, offset) => {
    const other = stages[(index + offset + 1) % stages.length]
    return {
      ko: other.ko,
      en: other.en,
    }
  })
}

function finalizeChapter(chapterOrder, title, description, rawStages) {
  return {
    chapterOrder,
    title,
    description,
    stages: rawStages.map((stage, index) => ({
      ...stage,
      stageOrder: index + 1,
      distractors: createDistractors(rawStages, index),
    })),
  }
}

function createWordChapter(chapterOrder, chapterKey, title, description, items, sentenceBuilder) {
  const rawStages = items.map(([ko, en]) => {
    const sentence = sentenceBuilder
      ? sentenceBuilder(ko, en)
      : {
          sentenceKo: `이것은 ${ko}입니다.`,
          sentenceEn: `This is ${article(en)} ${en}.`,
        }

    return {
      targetKey: `${chapterKey}_${en.toLowerCase().replace(/[^a-z0-9]+/g, '_')}`,
      ko,
      en,
      sentenceKo: sentence.sentenceKo,
      sentenceEn: sentence.sentenceEn,
    }
  })

  return finalizeChapter(chapterOrder, title, description, rawStages)
}

function createPatternChapter(chapterOrder, chapterKey, title, description, items, mapper) {
  const rawStages = items.map((item) => ({
    targetKey: `${chapterKey}_${item.slug}`,
    ...mapper(item),
  }))

  return finalizeChapter(chapterOrder, title, description, rawStages)
}

function createSentenceChapter(chapterOrder, chapterKey, title, description, items) {
  return createPatternChapter(
    chapterOrder,
    chapterKey,
    title,
    description,
    items.map(([slug, ko, en]) => ({ slug, ko, en })),
    (item) => ({
      ko: item.ko,
      en: item.en,
      sentenceKo: item.ko,
      sentenceEn: item.en,
    }),
  )
}

